-- ------------------------------------------------------------
-- 6. 只允许指定的两个邮箱注册（防止陌生人注册后看到数据）
--    换邮箱时同步修改下面的值
-- ------------------------------------------------------------
create or replace function public.block_uninvited_users()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if lower(coalesce(new.email, '')) not in ('me@example.com', 'friend@example.com') then
    raise exception 'Registration is closed';
  end if;
  return new;
end;
$$;

drop trigger if exists block_uninvited_users on auth.users;
create trigger block_uninvited_users
  before insert on auth.users
  for each row execute function public.block_uninvited_users();


