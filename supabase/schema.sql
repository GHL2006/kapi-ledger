-- ------------------------------------------------------------
-- 0. 用户资料表（跟随 auth.users 自动创建）
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  email        text,
  display_name text not null default '用户',
  created_at   timestamptz not null default now()
);

-- 新用户注册/后台创建时，自动插入 profiles
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ------------------------------------------------------------
-- 1. 分类表（预设分类 owner_id 为 null，用户新增分类带 owner_id）
-- ------------------------------------------------------------
create table if not exists public.categories (
  id         bigint generated by default as identity primary key,
  name       text not null unique,
  icon       text not null default '📦',
  color      text not null default '#A4B0BE',
  sort_order int not null default 0,
  owner_id   uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 2. 账单表
-- ------------------------------------------------------------
create table if not exists public.bills (
  id           bigint generated by default as identity primary key,
  amount       numeric(12, 2) not null check (amount > 0),
  category_id  bigint not null references public.categories(id),
  consume_time timestamptz not null,
  image_path   text,                 -- Supabase Storage 里的对象路径，如 uid/169999.jpg
  remark       text,
  owner_id     uuid not null references auth.users(id) on delete cascade,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 3. 资产 / 负债表（type: 1=资产，2=负债）
-- ------------------------------------------------------------
create table if not exists public.assets (
  id         bigint generated by default as identity primary key,
  type       smallint not null check (type in (1, 2)),
  name       text not null,
  amount     numeric(12, 2) not null check (amount >= 0),
  owner_id   uuid not null references auth.users(id) on delete cascade,
  remark     text,
  created_at timestamptz not null default now()
);

-- 索引
create index if not exists idx_bills_owner_time on public.bills (owner_id, consume_time desc);
create index if not exists idx_bills_category on public.bills (category_id);
create index if not exists idx_assets_owner on public.assets (owner_id);

-- updated_at 自动更新
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists bills_set_updated_at on public.bills;
create trigger bills_set_updated_at
  before update on public.bills
  for each row execute function public.set_updated_at();

